"""Webhook subscription management and the dead-letter view.

A department registers an endpoint here and stops polling. The secret is generated by
the platform rather than supplied by the subscriber -- a caller-chosen secret is
reliably a weak one, and there is no reason for the subscriber to pick it when they only
need to store it.

Like an API key token, the secret is returned once at creation and never again. The
stored copy is encrypted with the same scheme as camera credentials, and no endpoint
reads it back; the dispatcher is the only code that decrypts it.
"""

from __future__ import annotations

import secrets
import uuid
from datetime import datetime
from typing import Annotated, Any

from fastapi import APIRouter, Depends, Query
from pydantic import BaseModel, Field
from sqlalchemy import text
from sqlalchemy.orm import Session

from services.api import audit
from services.api.db import get_session
from services.api.errors import ApiError, ErrorCode
from services.api.security import AdminActor, CurrentActor
from services.api.webhooks import (
    EVENT_ID_HEADER,
    SIGNATURE_HEADER,
    SIGNATURE_VERSION,
    TIMESTAMP_HEADER,
    replay,
)
from services.common.credentials import CameraCredential, seal
from services.common.ssrf import SsrfBlocked, validate_uri

router = APIRouter(prefix="/webhooks", tags=["webhooks"])
SessionDep = Annotated[Session, Depends(get_session)]

#: Event types a subscription may ask for. A closed set, because a typo'd event type in
#: a subscription is a subscription that silently never fires.
EVENT_TYPES: tuple[str, ...] = (
    "alert.raised",
    "alert.acknowledged",
    "alert.resolved",
    "detection.created",
    "camera.status_changed",
)

_SECRET_WARNING = (
    "This secret is shown once and cannot be retrieved again. Store it now -- your "
    "receiver needs it to verify the signature on every delivery."
)


class CreateSubscriptionIn(BaseModel):
    name: str = Field(min_length=1, max_length=120)
    target_url: str = Field(description="https endpoint that will receive POSTs")
    event_types: list[str] = Field(description=f"Any of: {', '.join(EVENT_TYPES)}")
    department_id: uuid.UUID | None = Field(
        default=None, description="Omit for an estate-wide subscription (admin only)."
    )


class CreatedSubscriptionOut(BaseModel):
    id: uuid.UUID
    name: str
    target_url: str
    event_types: list[str]
    #: Shown once.
    secret: str
    signature_header: str
    timestamp_header: str
    event_id_header: str
    verification: str
    warning: str


class SubscriptionOut(BaseModel):
    id: str
    name: str
    target_url: str
    event_types: list[str]
    department_id: str | None
    active: bool
    created_at: datetime
    consecutive_failures: int
    disabled_at: datetime | None
    disabled_reason: str | None


class DeliveryOut(BaseModel):
    id: str
    subscription_id: str
    event_type: str
    event_id: str
    state: str
    attempts: int
    created_at: datetime
    delivered_at: datetime | None
    next_attempt_at: datetime | None
    last_status_code: int | None
    last_error: str | None
    attempt_log: list[dict[str, Any]]


_VERIFICATION = (
    f"signature = '{SIGNATURE_VERSION}=' + HMAC_SHA256(secret, timestamp + '.' + raw_body), "
    f"compared in constant time. Verify against the RAW request bytes, not a "
    f"re-serialised body. Reject a timestamp more than 300s from your clock -- without "
    f"that check a captured request replays forever. Deliveries are at-least-once: "
    f"deduplicate on the {EVENT_ID_HEADER} header."
)


@router.get("/event-types", response_model=list[str])
def event_types(actor: CurrentActor) -> list[str]:
    """What a subscription may ask for. A typo'd type never fires, so the set is closed."""
    return list(EVENT_TYPES)


@router.get("", response_model=list[SubscriptionOut])
def list_subscriptions(session: SessionDep, actor: CurrentActor) -> list[SubscriptionOut]:
    """Subscriptions the caller may see. RLS scopes this to their department."""
    rows = session.execute(
        text(
            "SELECT id, name, target_url, event_types, department_id, active, created_at,"
            "       consecutive_failures, disabled_at, disabled_reason"
            " FROM webhook_subscription ORDER BY created_at DESC"
        )
    ).mappings()
    return [
        SubscriptionOut(
            id=str(r["id"]),
            name=r["name"],
            target_url=r["target_url"],
            event_types=list(r["event_types"] or []),
            department_id=str(r["department_id"]) if r["department_id"] else None,
            active=bool(r["active"]) and r["disabled_at"] is None,
            created_at=r["created_at"],
            consecutive_failures=int(r["consecutive_failures"]),
            disabled_at=r["disabled_at"],
            disabled_reason=r["disabled_reason"],
        )
        for r in rows
    ]


@router.post("", response_model=CreatedSubscriptionOut, status_code=201)
def create_subscription(
    body: CreateSubscriptionIn, session: SessionDep, actor: AdminActor
) -> CreatedSubscriptionOut:
    """Register an endpoint. The secret is generated here and returned once."""
    unknown = sorted(set(body.event_types) - set(EVENT_TYPES))
    if unknown:
        raise ApiError(
            ErrorCode.VALIDATION_FAILED,
            f"unknown event types: {', '.join(unknown)}",
            detail={"valid": list(EVENT_TYPES)},
        )
    if not body.event_types:
        raise ApiError(
            ErrorCode.VALIDATION_FAILED, "a subscription with no event types never fires"
        )

    # The subscriber URL is operator-supplied, so it is exactly the user-controlled URL
    # the SSRF guard exists for. Validated at registration as well as at delivery, so a
    # bad URL is refused by the person who typed it rather than discovered by a
    # dispatcher at three in the morning.
    try:
        validate_uri(body.target_url)
    except SsrfBlocked as exc:
        raise ApiError(ErrorCode.VALIDATION_FAILED, f"target URL refused: {exc}") from exc

    subscription_id = uuid.uuid4()
    # Generated, not supplied. A caller-chosen secret is reliably a weak one, and the
    # subscriber has no reason to pick it when they only need to store it.
    secret = secrets.token_urlsafe(32)
    sealed = seal(
        CameraCredential(username="webhook", password=secret), camera_id=str(subscription_id)
    )

    import json

    session.execute(
        text(
            "INSERT INTO webhook_subscription (id, name, target_url, secret_ciphertext,"
            " secret_key_version, event_types, department_id, active, created_by,"
            " created_at, consecutive_failures)"
            " VALUES (:id, :name, :url, :cipher, :ver, CAST(:events AS jsonb), :dept,"
            " true, :by, now(), 0)"
        ),
        {
            "id": subscription_id,
            "name": body.name,
            "url": body.target_url,
            "cipher": sealed.ciphertext,
            "ver": sealed.key_version,
            "events": json.dumps(sorted(set(body.event_types))),
            "dept": body.department_id,
            "by": actor.subject,
        },
    )

    audit.append(
        session,
        action="REGISTER_WEBHOOK",
        subject_type="webhook_subscription",
        subject_id=str(subscription_id),
        actor_id=actor.subject,
        actor_role=actor.role,
        purpose=f"webhook subscription: {body.name}",
        # The URL is recorded; the secret never is.
        detail={
            "target_url": body.target_url,
            "event_types": sorted(set(body.event_types)),
            "department_id": str(body.department_id) if body.department_id else None,
        },
    )
    session.flush()

    return CreatedSubscriptionOut(
        id=subscription_id,
        name=body.name,
        target_url=body.target_url,
        event_types=sorted(set(body.event_types)),
        secret=secret,
        signature_header=SIGNATURE_HEADER,
        timestamp_header=TIMESTAMP_HEADER,
        event_id_header=EVENT_ID_HEADER,
        verification=_VERIFICATION,
        warning=_SECRET_WARNING,
    )


class ToggleOut(BaseModel):
    id: str
    active: bool
    detail: str


@router.post("/{subscription_id}/enable", response_model=ToggleOut)
def enable_subscription(
    subscription_id: uuid.UUID, session: SessionDep, actor: AdminActor
) -> ToggleOut:
    """Re-enable a subscription disabled by repeated failures.

    Clearing the failure counter is the point: without it the next failure would
    immediately re-trip the threshold.
    """
    updated = session.execute(
        text(
            "UPDATE webhook_subscription"
            "   SET active = true, disabled_at = NULL, disabled_reason = NULL,"
            "       consecutive_failures = 0"
            " WHERE id = :id RETURNING id"
        ),
        {"id": subscription_id},
    ).scalar()
    if updated is None:
        raise ApiError(ErrorCode.RESOURCE_NOT_FOUND, "no such subscription")
    session.flush()
    return ToggleOut(id=str(subscription_id), active=True, detail="queued deliveries will resume")


@router.delete("/{subscription_id}", response_model=ToggleOut)
def disable_subscription(
    subscription_id: uuid.UUID, session: SessionDep, actor: AdminActor
) -> ToggleOut:
    """Stop delivering. Queued rows are kept so the history stays readable."""
    updated = session.execute(
        text(
            "UPDATE webhook_subscription SET active = false, disabled_at = now(),"
            "       disabled_reason = 'disabled by an administrator'"
            " WHERE id = :id RETURNING id"
        ),
        {"id": subscription_id},
    ).scalar()
    if updated is None:
        raise ApiError(ErrorCode.RESOURCE_NOT_FOUND, "no such subscription")
    session.flush()
    return ToggleOut(id=str(subscription_id), active=False, detail="queued deliveries are retained")


@router.get("/deliveries", response_model=list[DeliveryOut])
def list_deliveries(
    session: SessionDep,
    actor: CurrentActor,
    state: str | None = Query(default=None, description="pending|delivering|delivered|failed|dead"),
    limit: int = Query(default=100, ge=1, le=1000),
) -> list[DeliveryOut]:
    """Deliveries, newest first. `state=dead` is the dead-letter view.

    The full attempt log travels with each row, because the useful question is not "did
    it fail" but "how, and how many times" -- which is what tells a department their
    endpoint is sick rather than this platform being unreliable.
    """
    rows = session.execute(
        text(
            "SELECT id, subscription_id, event_type, event_id, state, attempts, created_at,"
            "       delivered_at, next_attempt_at, last_status_code, last_error, attempt_log"
            " FROM webhook_delivery"
            " WHERE (:state IS NULL OR state = CAST(:state AS varchar(16)))"
            " ORDER BY created_at DESC LIMIT :limit"
        ),
        {"state": state, "limit": limit},
    ).mappings()
    return [
        DeliveryOut(
            id=str(r["id"]),
            subscription_id=str(r["subscription_id"]),
            event_type=r["event_type"],
            event_id=r["event_id"],
            state=r["state"],
            attempts=int(r["attempts"]),
            created_at=r["created_at"],
            delivered_at=r["delivered_at"],
            next_attempt_at=r["next_attempt_at"],
            last_status_code=r["last_status_code"],
            last_error=r["last_error"],
            attempt_log=list(r["attempt_log"] or []),
        )
        for r in rows
    ]


class ReplayOut(BaseModel):
    replayed: bool
    detail: str


@router.post("/deliveries/{delivery_id}/replay", response_model=ReplayOut)
def replay_delivery(delivery_id: uuid.UUID, session: SessionDep, actor: AdminActor) -> ReplayOut:
    """Re-queue a dead delivery. Its failure history is kept."""
    if not replay(session, delivery_id):
        raise ApiError(
            ErrorCode.CONFLICT,
            "only a dead delivery can be replayed; this one is live or does not exist",
        )
    audit.append(
        session,
        action="REPLAY_WEBHOOK_DELIVERY",
        subject_type="webhook_delivery",
        subject_id=str(delivery_id),
        actor_id=actor.subject,
        actor_role=actor.role,
        purpose="manual replay from the dead-letter view",
        detail={},
    )
    session.flush()
    return ReplayOut(
        replayed=True, detail="queued for the next dispatch; the attempt history is kept"
    )


